// Разбор надиктованной заметки.
//
// Схема ответа — та же, что у follow-up (FollowupSchema): задачи, решения,
// открытые вопросы, риски, обновления по проектам. Всё, что ниже по течению —
// база, страница «кто что должен», живое состояние проектов, публикация, —
// продолжает работать, ничего не зная про заметки.
//
// А промпт — свой, и это не украшение. Тот, что написан под созвон, половину
// сил тратит на разбор, кто из говорящих кто, и требует брать исполнителя из
// списка участников. В монологе участник один, список пуст, и правило
// начинает работать против: модель либо ставит «не назначен» там, где задача
// очевидно на говорящем, либо принимает упомянутого коллегу за исполнителя
// всего, что сказано рядом.
//
// Промпт написан по-русски и нарочно не обёрнут в i18n.Tr(). Язык ответа задаётся
// отдельно, строкой «Язык разбора» в шапке (claude.output_language). Сегодня
// уже поймали, чем кончается перевод промпта: подписи перевели, системную
// часть нет, и правила стали ссылаться на разделы, которых в тексте больше не
// было.

const noteSystem = `Ты разбираешь заметку, которую человек наговорил голосом — себе, вслух, чтобы не забыть.

Это не разговор. Говорит один человек, его имя названо в шапке. Он думает
вслух: ставит себе задачи, вспоминает, о чём надо кого-то спросить, проговаривает
решение, которое уже принял, и опасение, которое его беспокоит.

Твоя работа — сделать так, чтобы ничего из этого не потерялось. Заметку
наговаривают вместо того, чтобы записать; пункт, не попавший в разбор, не
записан больше нигде и пропадает совсем. Пропустить прозвучавшее — дороже,
чем сформулировать неточно.

## Кто исполнитель

Исполнитель по умолчанию — сам говорящий, имя бери из шапки. Это главное
отличие заметки от созвона: человек говорит о своих делах, и «надо», «не
забыть», «я хочу», «стоит», «сегодня же» — всё это его задачи.

Другой человек становится исполнителем только тогда, когда прямо сказано, что
дело уже на нём: «это на Вике», «Борис делает», «я попросил Ануара — он
доделывает». Одного упоминания мало.

«Надо попросить Вику посмотреть макет» — это задача говорящего: попросить.
Не задача Вики. Пока он её не попросил, у Вики никакой задачи нет.

Если человек говорит о себе в третьем лице или обращается к себе на «ты»
(«ладно, делай уже») — исполнитель всё равно он.

Оставлять "не назначен" в заметке почти никогда не нужно: у сказанного вслух
почти всегда есть хозяин, и это тот, кто говорит.

## Что обязано попасть

**Задача (action_items)** — всё, что нужно сделать.

В монологе размышление вслух — это и есть содержание, а не пустая болтовня:
здесь «хорошо бы переписать выгрузку» отличается от «перепишу выгрузку» только
уверенностью, и то и другое идёт в задачи. Не заводи задачу только из явно
отброшенного: «думал сделать отдельным сервисом — нет, не надо».

Отдельно смотри за тем, что человек назвал «не забыть», «главное — не
пропустить», «обязательно». Ради этого заметку и наговаривают: такой пункт
обязан оказаться в задачах, даже если сказан вскользь между двумя другими.

**Решение (decisions)** — выбор, после которого будут действовать иначе.
Решение, принятое в одиночку, — такое же решение: «решил не трогать схему»,
«остановился на sqlite», «делаем без докера». Отказ — тоже решение.

**Открытый вопрос (open_questions)** — то, что не решается в одиночку или не
решено:
- «надо спросить у Ануара, что с квотами» — вопрос, waiting_on: Ануар;
- «непонятно, потянет ли база» — вопрос без адресата, waiting_on: "не определено";
- «пока отложу, вернусь на следующей неделе» — тоже открытый вопрос.

**Риск (risks)** — то, что может пойти не так, и чем это грозит. В заметке
риск обычно звучит опасением: «боюсь, не успеем к пятнице», «если ключи
протухнут, встанет всё».

Когда кусок речи можно понять и как задачу, и как что-то ещё, он идёт в
задачи. «В пятницу надо прогнать всё на живом микрофоне, а то месяц назад так
же были уверены и потеряли два дня» — это задача со сроком, а опасение из
второй половины фразы — риск рядом с ней. Задача при этом не исчезает:
потерянная задача — самая дорогая ошибка разбора, и ни tldr, ни строчка в
рисках её не заменяют.

Один и тот же кусок речи не дублируй в двух списках, когда он и правда об
одном. «Надо спросить у Вики про макет, а до этого не начинаю вёрстку» — это
открытый вопрос (ждём Вику), а не ещё и задача «не начинать вёрстку».

## Как устроена речь вслух

1. Человек передумывает по ходу. «Сделаем на sqlite… хотя нет, там же
   параллельная запись, бери postgres» — это один пункт, и в нём postgres.
   Побеждает последний вариант, а не первый и не оба сразу.
2. Он говорит кусками, а не предложениями, и часто без связок. Соседние куски
   почти всегда об одном и том же — читай их вместе, а не по отдельности.
3. Он повторяет одну мысль дважды разными словами. Это один пункт.
4. Расшифровка машинная: в ней есть оговорки, обрывы и неверно распознанные
   слова. Восстанавливай смысл по соседям, но не додумывай факты.
5. Куски, которые явно не из речи — «спасибо за просмотр», «продолжение
   следует», «субтитры сделал…», «редактор субтитров», — мусор распознавания
   на тишине. Игнорируй их полностью.

## Как заполнять

6. owner — имя говорящего из шапки, кроме случаев, разобранных выше.
7. due — только если срок прозвучал. Относительные («к пятнице», «завтра»,
   «до конца недели») переводи в дату YYYY-MM-DD от даты заметки, она в шапке.
   Не прозвучал — пустая строка. Не выдумывай сроков: у заметки их обычно нет,
   и это нормально.
8. quote — дословный кусок расшифровки, из которого видно пункт. Не пересказ,
   не длиннее двух предложений.
9. at — время в секундах от начала записи, из той строки расшифровки, где это
   прозвучало. Оно превращается в ссылку на место в записи, по которой человек
   переслушает, если формулировка окажется непонятной.
10. tldr — от двух до четырёх строк: о чём заметка, а не пересказ по порядку.
11. title — короткая строка о содержании, как заголовок письма самому себе.
    Не "Заметка" и не "Голосовая заметка": по названию должно быть понятно, о
    чём она, среди двух десятков таких же.
12. timeline заполняй только у длинной заметки, где человек перешёл с темы на
    тему. У короткой оставь пустым: список из одного пункта «человек говорил»
    не нужен никому.
13. Пиши на том же языке, на котором говорили. Без вводных вроде «в этой
    заметке автор рассуждает» — сразу по делу.

## Чего не делать

14. Не выдумывай. Каждый пункт опирается на конкретное место в расшифровке.
    Ничего не решил — decisions пустой; но «не решил» и «я не нашёл, как это
    назвать» — разные вещи, и второе не повод для пустого списка.
15. Не превращай одну мысль в три пункта ради объёма. Заметка на минуту — это
    два-три пункта, и это правильный разбор.

## Проекты

16. У каждого решения, задачи и вопроса проставь project — название из списка
    проектов. Вслух проект называют иначе, чем он записан: ориентируйся на
    суть, а не на совпадение слов. Даны справки — разбирайся по ним, там
    записано, какими словами команда говорит о каждом проекте. Не относится ни
    к одному или непонятно — "не определён". Лучше "не определён", чем
    приписать чужому проекту.
17. У проектов бывают проставлены «люди» и «сервисы и сокращения». Это
    разметка, а не украшение: люди — те, на кого задачу назначить можно,
    сервисы и сокращения — те, на кого нельзя никогда, даже когда слово звучит
    как имя и стоит в предложении на месте человека.
18. Если в списке «что уже висит открытым» есть пункт, судьба которого решилась
    в этой заметке, добавь его в updates с его идентификатором: done —
    сделано, dropped — отменил или стало неактуально, still_open — говорил, но
    не закрыл (тогда note: что изменилось). Идентификаторы не выдумывай,
    только из списка. Заметка чаще всего именно про это: человек проговаривает
    вслух, что из висящего он сделал.
19. Пункт из «уже висит открытым», о котором говорили, идёт в updates, а не
    заново в action_items. Но если прозвучала новая задача, похожая на старую,
    — это новая задача. Сомневаешься — заводи новую: потерянная задача хуже,
    чем названная дважды.`

// noteHead — всё, что модель читает до расшифровки. Отдельно от followupHead,
// потому что говорит о другом: там список участников и приглашённых, здесь —
// один человек, чьим именем будут подписаны почти все задачи.
func noteHead(cfg *core.Config, m *core.Meeting, projects []core.Project, primers, openItems string) string {
	var head strings.Builder
	head.WriteString("Голосовая заметка.\n")
	fmt.Fprintf(&head, "Говорит один человек: %s. Задачи по умолчанию его.\n", noteAuthor(m))
	fmt.Fprintf(&head, "Дата: %s\n", m.StartedAt.Format("2006-01-02 15:04 MST"))
	if t := strings.TrimSpace(m.Title); t != "" && !isDefaultNoteTitle(t) {
		fmt.Fprintf(&head, "Человек назвал заметку так: %s\n", t)
	}
	if cfg != nil && cfg.Claude.OutputLanguage != "" {
		fmt.Fprintf(&head, "Язык разбора: %s\n", cfg.Claude.OutputLanguage)
	}

	if len(projects) > 0 {
		head.WriteString("\nПроекты команды:\n")
		for _, p := range projects {
			fmt.Fprintf(&head, "  %s", p.Name)
			if len(p.Aliases) > 0 {
				fmt.Fprintf(&head, " (вслух: %s)", strings.Join(p.Aliases, ", "))
			}
			if p.About != "" {
				fmt.Fprintf(&head, " — %s", p.About)
			}
			head.WriteString("\n")
			// Люди и не-люди — двумя строками, как в follow-up. Плоский список
			// оставляет модель гадать по звучанию, кто из них человек, а ошибка
			// в эту сторону — это задача, уехавшая на сервис.
			if len(p.People) > 0 {
				fmt.Fprintf(&head, "    люди: %s\n", strings.Join(p.People, ", "))
			}
			if other := p.OtherWords(); len(other) > 0 {
				fmt.Fprintf(&head, "    сервисы и сокращения (не люди): %s\n",
					strings.Join(other, ", "))
			}
		}
		fmt.Fprintf(&head, "  %s — если непонятно, к чему относится\n", core.UnassignedProject)
	}
	if primers != "" {
		head.WriteString("\n")
		head.WriteString(primers)
	}
	if openItems != "" {
		head.WriteString("\n")
		head.WriteString(openItems)
	}
	head.WriteString("\nРасшифровка, одна строка — один кусок речи, в скобках время от начала:\n\n")
	return head.String()
}

// renderMonologue — расшифровка так, как её читает модель.
//
// Отдельно от RenderTranscript, и вот почему: тот склеивает подряд идущие
// реплики одного человека в одну строку с одним таймкодом. На созвоне это
// помогает — вместо лесенки из «А: ага» получается связная речь. В монологе
// говорящий один, склеивается вся заметка целиком, и от таймкодов остаётся
// ровно один — нулевой. Ссылка «переслушать это место» после такого ведёт на
// начало записи, что бы ни было в пункте.
func renderMonologue(segs []core.Segment) string {
	var b strings.Builder
	for _, s := range segs {
		txt := strings.TrimSpace(s.Text)
		if txt == "" {
			continue
		}
		fmt.Fprintf(&b, "[%s] %s\n", core.Clock(s.Start), txt)
	}
	return b.String()
}

// noteAuthor — чьё имя ставить исполнителем. Участник у заметки ровно один:
// его записали при старте записи.
func noteAuthor(m *core.Meeting) string {
	if m != nil {
		for _, p := range m.Participants {
			if s := strings.TrimSpace(p); s != "" {
				return s
			}
		}
	}
	return defaultNoteAuthor
}

func makeNote(ctx context.Context, cfg *core.Config, m *core.Meeting, segs []core.Segment,
	projects []core.Project, primers, openItems string) (*core.Followup, core.Spend, error) {

	maxTokens := int64(cfg.Claude.MaxTokens)
	if maxTokens <= 0 {
		maxTokens = 16000
	}
	out, spend, err := brain.AskLLM(ctx, cfg, noteSystem,
		noteHead(cfg, m, projects, primers, openItems)+renderMonologue(segs),
		brain.FollowupSchema(), maxTokens)
	if err != nil {
		return nil, core.Spend{}, err
	}

	var f core.Followup
	if err := json.Unmarshal([]byte(out), &f); err != nil {
		return nil, core.Spend{}, fmt.Errorf(i18n.Tr("разбор заметки: %w\nответ: %.400s"), err, out)
	}
	// Названия проектов приводим к тем, что записаны в конфиге, — как и у
	// follow-up: модель возвращает «биллинг» там, где проект зовётся «Платежи».
	for i := range f.ActionItems {
		f.ActionItems[i].Project = core.MatchProject(projects, f.ActionItems[i].Project)
		// Пустого исполнителя у заметки быть не должно: сказанное вслух —
		// дело говорящего, и «не назначен» здесь означает только то, что
		// модель поленилась подставить имя из шапки.
		if strings.TrimSpace(f.ActionItems[i].Owner) == "" {
			f.ActionItems[i].Owner = noteAuthor(m)
		}
	}
	for i := range f.Decisions {
		f.Decisions[i].Project = core.MatchProject(projects, f.Decisions[i].Project)
	}
	for i := range f.OpenQuestions {
		f.OpenQuestions[i].Project = core.MatchProject(projects, f.OpenQuestions[i].Project)
	}
	return &f, spend, nil
}

// noteTitle — как заметка называется, пока Claude не придумал ей название.
// Дата с временем, потому что заметок за день бывает несколько, и в списке
// они должны различаться.
func noteTitle(at time.Time) string {
	return i18n.Trf("Заметка %s", at.Format("02.01 15:04"))
}

// isDefaultNoteTitle — не показывать модели название, которое придумали за
// человека: «Заметка 10.09 14:35» она честно попробует использовать.
func isDefaultNoteTitle(s string) bool {
	return strings.HasPrefix(s, i18n.Tr("Заметка ")) || strings.HasPrefix(s, "Заметка ")
}
