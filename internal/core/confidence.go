package core

import "strings"

// Уверенность распознавания — вторая половина того, что движок на самом деле
// знает о звуке, и до сих пор мы её выбрасывали.
//
// Whisper — языковая модель: она всегда выбирает самое вероятное продолжение и
// никогда не говорит «не расслышал». На записи созвона это выглядит так:
// «Орынгали нужно закончить Сапар» превращается в «Анвару нужно закончить
// сапар», и с виду это обычная строка расшифровки — задача просто уезжает не на
// того человека. Никакой промпт этого не чинит: чинить нечего, текст выглядит
// нормальным.
//
// Но само число у движка есть. Whisper печатает вероятность каждого токена
// (whisper-cli -ojf), коммерческие движки — уверенность каждого слова. Замер на
// записи владельца (два созвона, 79 слов):
//
//	Анвару      0.33   ← ошибка, поймана
//	сапар       0.28   ← ошибка, поймана
//	выпустили   0.06   ← на этом месте пропал «релиз», поймана
//	завтра      0.38   ← обрывок «послезавтра», поймана
//	пешные      0.84   ← ошибка, НЕ поймана
//	участники   1.00   ← верно
//	закончить   0.99   ← верно
//
// Отсюда два вывода, на которых стоит всё остальное в этом файле.
//
// Первый: уверенность нужна по словам, а не по реплике. «Пешные» стоит в
// реплике «чтобы участники нормальные и пешные могли участвовать», где
// остальные слова идут по 0.78–1.00; средняя по реплике вышла бы 0.75 и не
// отличалась бы ни от чего. Ошибка — одно слово, и ловится она только на
// уровне слова.
//
// Второй: пометка честная, а не всезнающая. «Пешные» не помечено — зато
// помечены два слова прямо перед ним («нормальные» 0.30 и «и» 0.50). Так
// устроена авторегрессия: сомнение приходится на развилку, а дальше модель
// уверенно идёт по уже выбранной ветке. Поэтому пометка говорит «здесь
// расслышано плохо», а не «вот это слово неверное», и правило разбора должно
// быть написано ровно так.

// Word — одно слово расшифровки с уверенностью движка.
//
// Conf — указатель, и это не украшение. nil означает «движок не сказал», ноль
// означает «движок сказал: почти наверняка мусор». Спутать их — значит объявить
// хорошую расшифровку от whisper.cpp без -ojf сплошным сомнительным местом.
type Word struct {
	Word  string   `json:"word"`
	Start float64  `json:"start"`
	End   float64  `json:"end"`
	Conf  *float64 `json:"conf,omitempty"`
}

// UncertainBelow — ниже этого слово считается плохо расслышанным.
//
// Померено на двух записях владельца, 79 слов. При 0.5 пометку получают 9 слов
// (11%), при 0.4 — семь, при 0.6 — шестнадцать (20%), и на двадцати процентах
// пометка перестаёт что-либо значить.
//
// Между 0.4 и 0.5 замер не выбирает: ловят они одно и то же, разница в двух
// верно распознанных названиях («VLive» 0.42, «транскрипт» 0.41), то есть в
// двух ложных срабатываниях. Выбрано 0.5, и вот почему: самое высокое из
// пойманных настоящих искажений — обрывок срока «завтра» с 0.379. Порог 0.4
// прошёл бы над ним с зазором в две сотых, а мерено это на 79 словах. Ложная
// пометка стоит модели одного лишнего «(?)», которое она прочтёт и пройдёт
// мимо; пропущенная — задачи, уехавшей не на того человека.
const UncertainBelow = 0.5

// UncertainMark — чем помечаем. Прямо в тексте, рядом со словом, а не отдельным
// списком в конце: модель читает расшифровку подряд, и «на кого назначена
// задача» решается ровно в том месте, где стоит имя. Список в конце заставил бы
// её искать слово обратно по тексту, где оно к тому же может повторяться, и
// стоил бы расшифровки дважды в токенах.
const UncertainMark = "(?)"

// Uncertain — сказал ли движок, что расслышал плохо. Отдельной функцией, чтобы
// «не сказал» и «сказал ноль» нигде не смешались случайно.
func Uncertain(c *float64) bool { return c != nil && *c < UncertainBelow }

// MarkUncertain возвращает текст реплики с пометками у плохо расслышанных слов.
//
// Пометки вставляются в исходный текст, а не текст собирается заново из слов:
// разбивка на слова у разных движков своя, и собранная заново строка потеряла
// бы пунктуацию и пробелы ровно там, где движок разошёлся с нами во мнении, что
// такое слово. Слово, которого в тексте не нашлось, молча пропускается — текст
// дороже пометки.
//
// Слов нет вовсе, а уверенность реплики низкая — помечается вся реплика
// целиком: так отвечают движки, у которых уверенность есть только на реплику.
func MarkUncertain(s Segment) string {
	txt := strings.TrimSpace(s.Text)
	if txt == "" {
		return txt
	}
	if len(s.Words) == 0 {
		if Uncertain(s.Conf) {
			return txt + UncertainMark
		}
		return txt
	}
	var b strings.Builder
	written, search := 0, 0
	for _, w := range s.Words {
		word := strings.TrimSpace(w.Word)
		if word == "" {
			continue
		}
		at := strings.Index(txt[search:], word)
		if at < 0 {
			continue
		}
		end := search + at + len(word)
		search = end
		if !Uncertain(w.Conf) {
			continue
		}
		b.WriteString(txt[written:end])
		b.WriteString(UncertainMark)
		written = end
	}
	if written == 0 {
		return txt
	}
	b.WriteString(txt[written:])
	return b.String()
}

// CountUncertain — сколько слов расшифровки помечено и сколько их всего.
// Нужно, чтобы человек видел в логе, работает ли уверенность вообще: движок без
// неё даёт 0 из 0, и это сразу отличается от «всё расслышано хорошо».
func CountUncertain(segs []Segment) (marked, total int) {
	for _, s := range segs {
		for _, w := range s.Words {
			if strings.TrimSpace(w.Word) == "" {
				continue
			}
			total++
			if Uncertain(w.Conf) {
				marked++
			}
		}
	}
	return marked, total
}
