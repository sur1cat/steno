// Словарь созвона — слова, которые whisper слышит, но не знает.
//
// Настоящий случай. На созвоне сказали «Орынгали нужно закончить Сапар».
// В расшифровке вышло «Анвару нужно закончить сапар»: Орынгали — имя человека
// из коммитов taxi-kolesa, Сапар — сервис worker_sapar из docker-compose того
// же проекта. Ни того, ни другого нет в словаре модели, и она подставила
// похожее знакомое слово. Задача уехала не на того человека, а сервис стал
// обычным словом со строчной буквы.
//
// Задним числом это не чинится: из «Анвару» имя не восстановить никаким
// follow-up. Чинится только до распознавания — подсказкой (--prompt), которую
// whisper держит перед глазами, пока слушает, и в которой лежат нужные слова.
//
// Слова берём оттуда же, откуда справку о проекте (context.go), теми же
// функциями: авторы коммитов, сервисы docker-compose, модули верхнего уровня.
// Не разбором готовой справки: справку пишет модель свободным текстом, и
// вытаскивать из неё список — значит завязать распознавание на то, каким
// абзацем модель сегодня решила ответить. Плюс два источника, которых в
// справке нет вовсе: имена участников созвона (они пришли из аккаунтов Google
// и всегда верные) и названия самих проектов с псевдонимами.
//
// Собирается это прямо перед расшифровкой, а не хранится рядом со справкой.
// Причин две. Во-первых, дёшево: git log и пара ReadDir на проект — доли
// секунды перед прогоном, который идёт минуты. Во-вторых, свежо: человека,
// пришедшего в проект вчера, справка узнает только на следующей пересборке, а
// расшифровке он нужен уже сегодня.
//
// Главное, что стоит знать про всё это, прежде чем что-то тут менять:
// подсказка исправляет слово только тогда, когда содержит его ровно в том
// виде, в каком оно должно попасть в расшифровку. Проверено на записи созвона:
// со словом «Сапар» в подсказке whisper пишет «Сапар», без него — «сапар»,
// а от «worker_sapar» и «sapar» не меняется ничего. То же с именами: подпись
// в git «Oryngali Karimzhan» на русскую речь не действует, «Орынгали» —
// действует. Поэтому добытое из репозитория стоит в очереди последним, а
// первыми — слова, которые человек написал так, как их произносят.

// promptTokens — сколько токенов подсказки принимает whisper. Ровно половина
// текстового контекста модели: whisper_full берёт из истории не больше
// n_text_ctx/2, а n_text_ctx у всех моделей whisper равен 448.
//
// Бюджет — ниже жёсткого предела whisper (224 токена, дальше он режет
// подсказку с начала, то есть по именам людей), но с запасом на всё, что
// человек вписал руками.
//
// История числа. Сначала стояло 60: на списке через запятую подсказка на 160
// токенов не исправила ни одного слова и слепила тринадцать реплик в две.
// Но список давно заменён фразой (см. Prompt), а разбивка на реплики с тех
// пор берётся из прохода без подсказки (см. merge.go) — длина фразы её больше
// не трогает. Осталась одна цена — сама точность. И она перепроверена на живом
// созвоне 2026-09-11: фраза на 92 по этой оценке (шесть человек, участник,
// пять названий) исправила «Апаром» → «Сапаром» и «для нас» → «Гульнас», не
// вставив ни одного лишнего слова. А потолок 60 на том же созвоне отрезал
// шестое имя — «Гульназ», вписанное руками, — и задача осталась без
// исполнителя. Оценка wordTokens завышает настоящие токены примерно в
// полтора раза, так что 160 здесь — это около ста настоящих.
const promptTokenLimit = 224
const promptBudget = 160

// termsLimit — сколько слов уходит движку с настоящим входом для словаря
// (STENO_TERMS: AssemblyAI и подобные). Там нет бюджета whisper: словарь не
// притворяется текстом и разбивку не ломает, AssemblyAI принимает до тысячи
// слов. Сто — это весь словарь двух живых проектов с запасом; проект с
// полусотней сервисов и десятком людей укладывается целиком, а хвост длиннее
// сотни — уже не словарь, а перечень каталогов.
const termsLimit = 100

// Vocab — словарь, разложенный по важности. Порядок здесь не косметика: в
// подсказку влезает четыре-пять слов, а у проекта с полусотней сервисов и
// десятком человек их набирается на порядок больше. Что-то придётся отсечь, и
// отсекать надо с конца.
//
// Имена людей идут первыми, потому что цена ошибки у них выше. Незнакомый
// сервис whisper запишет строчной буквой и похожим словом — follow-up об этом
// споткнётся, но текст останется читаемым. Незнакомое имя превращается в
// другое слово целиком, и вместе с ним пропадает, на ком задача.
//
// Раньше имён и названий, добытых из репозитория, идёт всё, что известно
// точно: участники созвона, люди и слова, вписанные человеком, названия самих
// проектов. Разница между этими двумя источниками не в надёжности данных, а в
// том, той ли они формы. В git человек подписан «Oryngali Karimzhan», в
// docker-compose сервис зовётся «worker_sapar», а на созвоне звучат «Орынгали»
// и «Сапар» — и это проверено на записи: подсказка исправляет слово только
// тогда, когда содержит его в том виде, в каком оно должно попасть в
// расшифровку. От латинского «worker_sapar» кириллическое «сапар» не
// исправилось ни разу, от «Сапар» — исправилось. Поэтому добытое из
// репозитория стоит в очереди последним: на английском созвоне оно работает,
// на русском занимает место.
//
// Каждый из четырёх списков разбит на источники — созвон и каждый проект
// отдельно, — и в подсказку они идут вперемешку по кругу: первое слово каждого
// источника, потом второе каждого, и так далее. Иначе места хватает только
// первому по алфавиту: на живой паре проектов словарь steno выбирал бюджет
// целиком, и taxi-kolesa, о котором и шёл разговор, не попадал в подсказку ни
// одним словом.
type Vocab struct {
	// Lang — язык, на котором строится фраза подсказки (Prompt): "ru" —
	// по-русски, всё остальное — по-английски. Пусто — язык интерфейса.
	// Фраза должна быть на языке речи: whisper продолжает её как текст, и
	// русская подводка перед английским созвоном — это просьба переводить.
	Lang string

	people, terms           [][]string // известно точно
	minedPeople, minedTerms [][]string // добыто из репозитория
	seen                    map[string]bool
}

// source открывает новый источник — созвон или очередной проект.
func (v *Vocab) source() {
	for _, g := range []*[][]string{&v.people, &v.terms, &v.minedPeople, &v.minedTerms} {
		*g = append(*g, nil)
	}
}

// add — общая часть обоих списков: дубликаты и мусор дальше не идут. Место в
// подсказке дорогое, а одно и то же имя человек заводит и в участниках, и в
// коммитах, и в ручном словаре.
func (v *Vocab) add(groups *[][]string, words []string) {
	if v.seen == nil {
		v.seen = map[string]bool{}
	}
	if len(*groups) == 0 {
		v.source()
	}
	for _, w := range words {
		w = strings.TrimSpace(w)
		if !usefulWord(w) {
			continue
		}
		key := strings.ToLower(w)
		if v.seen[key] {
			continue
		}
		v.seen[key] = true
		g := *groups
		g[len(g)-1] = append(g[len(g)-1], w)
	}
}

func (v *Vocab) addPeople(names ...string)      { v.add(&v.people, names) }
func (v *Vocab) addTerms(names ...string)       { v.add(&v.terms, names) }
func (v *Vocab) addMinedPeople(names ...string) { v.add(&v.minedPeople, names) }
func (v *Vocab) addMinedTerms(names ...string)  { v.add(&v.minedTerms, names) }

// byTurns — слова источников по кругу: первое каждого, второе каждого и так
// далее. Порядок внутри источника при этом сохраняется.
func byTurns(groups [][]string) []string {
	var out []string
	for turn := 0; ; turn++ {
		took := false
		for _, g := range groups {
			if turn < len(g) {
				out = append(out, g[turn])
				took = true
			}
		}
		if !took {
			return out
		}
	}
}

// usefulWord отсеивает то, что в подсказке только занимает место. Слово из
// одной буквы whisper и так знает; строку длиной с предложение мы получаем,
// когда в участниках оказывается не человек, а надпись со страницы Meet —
// «Others might still see your full video» попадала в участников целиком.
func usefulWord(w string) bool {
	if n := len([]rune(w)); n < 2 || n > 40 {
		return false
	}
	if strings.Count(w, " ") > 3 {
		return false
	}
	// Хотя бы одна буква: «---» и «v2.1» словарём не являются.
	for _, r := range w {
		if unicode.IsLetter(r) {
			return true
		}
	}
	return false
}

// MeetingVocabulary — словарь для одного созвона: кто на нём был и чем живут
// проекты. Проект на момент расшифровки ещё не выбран — его определяет
// follow-up по тексту, которого пока нет, — поэтому берём слова всех проектов
// сразу. Отсюда и теснота бюджета.
//
// nil означает «подсказывать нечего», и RunTranscriber тогда зовёт адаптер
// один раз, ровно как до всей этой истории.
func MeetingVocabulary(ctx context.Context, cfg *core.Config, st *core.Store, m *core.Meeting) *Vocab {
	if cfg == nil || !cfg.Transcribe.Vocabulary {
		return nil
	}
	projects := vocabProjects(st, cfg)
	if !anyHandWritten(projects) {
		// Замерено на живых записях: словарь, собранный только из репозитория
		// и названий проектов, не исправил ни одного слова — латиница не
		// действует на кириллическую речь, — но разбивку на реплики сломал
		// (13 реплик слиплись в 2, а от длины реплики зависит имя говорящего).
		// Подсказка окупается ровно тогда, когда в ней лежат те самые слова,
		// на которых распознавание уже ошиблось. Их вписывают руками в
		// «кто участвует» и «сервисы и сокращения»; пока там пусто, молчим.
		return nil
	}
	v := &Vocab{Lang: promptLang(cfg)}
	for _, p := range projects {
		v.source()
		v.addProject(ctx, cfg.DataDir, p)
	}
	if m != nil {
		// Участники — последним источником, хотя имена у них самые надёжные:
		// они пришли из аккаунтов Google. Беда в том, что пришли латиницей, а
		// замерено, что латиница на кириллическую речь не действует вовсе.
		// Во фразу влезает четыре-пять слов, и «Rustem Turgeldin» в первом
		// слоте вытеснил бы «Орынгали», вписанного руками ровно потому, что
		// распознавание на нём споткнулось.
		v.source()
		v.addPeople(m.Participants...)
	}
	return v
}

// promptLang — на каком языке строить фразу подсказки. Язык распознавания,
// если он задан; иначе — язык интерфейса, потому что при автоопределении язык
// речи известен только адаптеру, и уже после того, как подсказка собрана.
// Русский интерфейс у человека, чьи созвоны идут по-русски, — догадка куда
// точнее, чем всегда английский.
func promptLang(cfg *core.Config) string {
	if l := strings.TrimSpace(cfg.Transcribe.Language); l != "" && !strings.EqualFold(l, "auto") {
		return l
	}
	return i18n.UILang
}

// anyHandWritten — вписал ли человек хоть одно слово сам. Псевдонимы сюда не
// считаются: их заполняют, чтобы модель узнала проект по разговорному имени,
// а не потому, что whisper на них спотыкался.
func anyHandWritten(projects []core.Project) bool {
	for _, p := range projects {
		if len(p.People) > 0 || len(p.Vocabulary) > 0 {
			return true
		}
	}
	return false
}

// vocabProjects — то же, что ActiveProjects, но переживает отсутствие базы:
// RunTranscriber зовут и из doctor, и из тестов, где Store нет вовсе.
func vocabProjects(st *core.Store, cfg *core.Config) []core.Project {
	if st != nil {
		return core.ActiveProjects(st, cfg)
	}
	return cfg.Projects
}

// addProject — слова одного проекта.
func (v *Vocab) addProject(ctx context.Context, dataDir string, p core.Project) {
	// Имена, которые человек вписал руками, — самые точные из всего, что есть
	// про проект: в git он «TomXemmings», а на созвоне звучит «Рустем». Они же
	// лежат и в общем словаре, но там бы попали в один список с сервисами и при
	// нехватке места отсеклись бы наравне с ними.
	v.addPeople(p.People...)
	// Ручной словарь идёт раньше названия проекта и псевдонимов, а те — раньше
	// добытого из репозитория. Ручной словарь человек написал затем, что
	// распознавание уже ошиблось на этих словах; название и псевдонимы
	// заполняют, чтобы модель узнала проект по разговорному имени, — whisper
	// на них не спотыкался. Пока подсказка была списком на дюжину слов,
	// порядок внутри «известного точно» не решал; во фразу влезает четыре-пять
	// слов, и слуг репозитория вроде «taxi-kolesa» впереди «Сапар» хватило бы,
	// чтобы «Сапар» в подсказку не попал.
	v.addTerms(p.Vocabulary...)
	v.addTerms(p.Name)
	v.addTerms(p.Aliases...)
	for _, src := range p.Sources {
		dir := vocabRepoDir(dataDir, p, src)
		if dir == "" {
			continue
		}
		v.addMinedPeople(brain.RepoAuthorNames(ctx, dir)...)
		v.addMinedTerms(brain.ComposeServices(dir)...)
		v.addMinedTerms(brain.TopModuleNames(dir)...)
	}
}

// vocabRepoDir — где лежит репозиторий проекта. Клонировать здесь нельзя:
// подсказка собирается за секунды до расшифровки, и ходить за ней в сеть
// значит ставить расшифровку в зависимость от того, доступен ли сейчас
// GitHub. Клон, сделанный при сборке справки, берём; нет его — обходимся тем,
// что есть.
func vocabRepoDir(dataDir string, p core.Project, src core.Source) string {
	var dir string
	switch src.Kind {
	case "path":
		dir = brain.ExpandHome(src.Value)
	case "repo":
		dir = filepath.Join(dataDir, "repos", brain.SafeName(p.Name))
	default:
		return ""
	}
	if st, err := os.Stat(dir); err != nil || !st.IsDir() {
		return ""
	}
	return dir
}

// Prompt — подсказка для whisper: короткая фраза с точками, обрезанная по
// бюджету. Люди — в одном предложении, названия — в другом:
//
//	Созвон команды разработки. Участвуют Ануар и Рустем. Обсуждают Сапар.
//
// Фраза, а не список через запятую, — и это измерено на 63 прогонах whisper по
// двум настоящим записям, а не выбрано на вкус. Whisper продолжает подсказку
// как текст, поэтому её форма протекает в расшифровку — и в слова, и в
// разбивку на реплики:
//
//   - «Ануар, Сапар, steno.» — список рушит границы: из тринадцати реплик
//     на своих местах остаются одна-три, а между «закончить» и «Сапар»
//     появляется «с», которого никто не говорил;
//   - «Созвон команды разработки. Участвуют Ануар и Рустем. Обсуждают
//     Сапар.» — та же горсть слов фразой держит границы (десять реплик из
//     тринадцати на месте против одной-трёх) и ничего лишнего не вставляет.
//     Имена при этом чинятся так же: «Ануар», «Сапар»;
//   - «Участники: Ануар, Рустем. Сервисы: Сапар, SDK.» — перечни через
//     двоеточие внутри фразы ведут себя как список: одна-две реплики из
//     тринадцати.
//
// Разбивка второго прохода в итоге не решает — границы берутся из прохода без
// подсказки (merge.go), — но лишние слова из второго прохода в расшифровку
// попадают, и фраза их не даёт.
//
// Слова добавляются по важности (см. Vocab) до первого, которое не влезло в
// бюджет, а не с пропуском его в пользу следующего покороче: набивать хвост
// мелкими словами, выкинув крупное важное, — не экономия, а подмена. Меряется
// вся фраза целиком, вместе с каркасом: у whisper бюджет один на всё.
func (v *Vocab) Prompt(budget int) string {
	lang := v.Lang
	if lang == "" {
		lang = i18n.UILang
	}
	t := promptTemplate(lang)
	var people, terms []string
	best := ""
	add := func(dst *[]string, w string) bool {
		*dst = append(*dst, w)
		s := t.render(people, terms)
		if wordTokens(s) > budget {
			*dst = (*dst)[:len(*dst)-1]
			return false
		}
		best = s
		return true
	}
	for _, g := range []struct {
		dst    *[]string
		groups [][]string
	}{{&people, v.people}, {&terms, v.terms}, {&people, v.minedPeople}, {&terms, v.minedTerms}} {
		for _, w := range byTurns(g.groups) {
			if !add(g.dst, w) {
				return best
			}
		}
	}
	return best
}

// Terms — словарь списком, для движков с настоящим входом для словаря
// (STENO_TERMS). Тот же порядок по важности, что и во фразе, но без бюджета
// whisper: там словарь не притворяется текстом.
func (v *Vocab) Terms() []string {
	var out []string
	for _, g := range [][][]string{v.people, v.terms, v.minedPeople, v.minedTerms} {
		out = append(out, byTurns(g)...)
	}
	if len(out) > termsLimit {
		out = out[:termsLimit]
	}
	return out
}

// promptShape — каркас фразы подсказки на одном языке.
//
// Русский текст дословно тот, что мерился (S1 из замера); английский —
// его перевод, на английской записи не мерился. Число глагола согласуется с
// числом людей: «Участвует Рустем» для заметки на один голос.
type promptShape struct {
	lead      string // вводное предложение
	one, many string // предложение про людей: один человек и несколько
	terms     string // предложение про названия
	and       string // союз перед последним словом перечня
}

func (t promptShape) render(people, terms []string) string {
	if len(people) == 0 && len(terms) == 0 {
		return ""
	}
	s := t.lead
	if len(people) == 1 {
		s += " " + fmt.Sprintf(t.one, people[0])
	} else if len(people) > 1 {
		s += " " + fmt.Sprintf(t.many, t.list(people))
	}
	if len(terms) > 0 {
		s += " " + fmt.Sprintf(t.terms, t.list(terms))
	}
	return s
}

// list — «Ануар, Рустем и Орынгали»: перечень внутри предложения, а не
// список. Двоеточие с перечнем через запятую whisper читает как список — и
// ведёт себя как со списком (см. Prompt).
func (t promptShape) list(ws []string) string {
	if len(ws) == 1 {
		return ws[0]
	}
	return strings.Join(ws[:len(ws)-1], ", ") + " " + t.and + " " + ws[len(ws)-1]
}

func promptTemplate(lang string) promptShape {
	if strings.HasPrefix(strings.ToLower(strings.TrimSpace(lang)), "ru") {
		return promptShape{
			lead:  "Созвон команды разработки.",
			one:   "Участвует %s.",
			many:  "Участвуют %s.",
			terms: "Обсуждают %s.",
			and:   "и",
		}
	}
	return promptShape{
		lead:  "Development team call.",
		one:   "%s takes part.",
		many:  "%s take part.",
		terms: "They discuss %s.",
		and:   "and",
	}
}

// wordTokens — грубая оценка длины слова в токенах BPE, которым whisper режет
// подсказку. Токенизатор лежит внутри модели, и повторить его здесь нечем,
// поэтому оценка калибрована по самому whisper: он печатает точное число
// токенов, когда подсказка не влезает в -mc. На ggml-large-v3 замерено:
//
//	«Орынгали, Рустем Тургельдин, Сапар, worker_sapar, МДС, VLive.» — 33
//	«Орынгали, Айгерим, Данияр, Жанибек, Мадина, Рустем.»           — 29
//	«worker_sapar, billing, webhook, migrations, onboarding.»       — 17
//
// Формула на тех же строках даёт 36, 34 и 24 — то есть никогда не меньше
// настоящего. Ошибаться она должна именно в эту сторону: недооценка означала
// бы, что подсказку обрежет уже сам whisper, и обрежет с начала — по именам
// людей. Запас в этом же и расходуется: бюджет ниже потолка whisper.
//
// Кириллица дороже латиницы почти вдвое на символ: на русском BPE whisper
// даёт примерно полтора символа на токен, на английском — два с половиной.
func wordTokens(s string) int {
	ascii, other := 0, 0
	for _, r := range s {
		switch {
		case unicode.IsSpace(r):
			other++ // пробел внутри «Рустем Тургельдин» — отдельный токен
		case r > unicode.MaxASCII:
			other++
		default:
			ascii++
		}
	}
	return (7*other + 4*ascii + 9) / 10
}
