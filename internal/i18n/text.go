package i18n

import "fmt"

// Обрезка и согласование — текст, который увидит человек.
//
// Эти три функции лежат здесь не по смыслу пакета, а потому, что ниже i18n
// ничего нет, а нужны они всем: core, brain, audio, sources, publish, tui и
// самим тестам каталога переводов. Cut и Tail режут по символам, а не по
// байтам, — иначе кириллица рвётся пополам на стыке.

// Cut режет по символам, а не по байтам: обрезанный по байту текст с
// кириллицей теряет половину буквы на стыке.
func Cut(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n]) + "\n…"
}

// Tail режет по символам, а не по байтам: обрезанный по байту текст ошибки с
// кириллицей уходит в базу с половиной буквы на стыке.
func Tail(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return "…" + string(r[len(r)-n:])
}

// Plural — то же согласование, что и в панели: «1 коммит», «2 коммита»,
// «5 коммитов». Машинный текст в чате команды читают каждый день.
func Plural(n int, one, few, many string) string {
	w := many
	switch {
	case n%10 == 1 && n%100 != 11:
		w = one
	case n%10 >= 2 && n%10 <= 4 && (n%100 < 12 || n%100 > 14):
		w = many
		if n%100 < 12 || n%100 > 14 {
			w = few
		}
	}
	return fmt.Sprintf("%d %s", n, w)
}
