package google

import "github.com/sur1cat/steno/internal/i18n"

// Тесты проверяют русский вывод — на нём написан исходник, и он же служит
// ключом каталога. Английский проверяется отдельно, в internal/i18n.
//
// Раньше это стояло одной строкой в i18n_lang_test.go: пакет был один, и
// одного init хватало на все тесты сразу. После разбора у каждого пакета свой
// тестовый бинарник, и язык ему надо выставлять свой — иначе на машине без
// русской локали (в CI это так) половина проверок сравнивает русский текст
// с английским.
func init() { i18n.UILang = i18n.LangRU }
